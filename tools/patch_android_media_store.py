#!/usr/bin/env python3
"""Patch the scaffolded Android runner with the Wavely MediaStore bridge.

The repo does not commit platform runner folders (see README "Getting
Started"): they are generated by `flutter create .`. This script writes the
`wavely/media_store` MethodChannel handler over the template MainActivity and
declares the media permissions on the manifest.

Why: on Android 10+ scoped storage, walking `/storage/emulated/0/Music`
with dart:io returns nothing for third-party audio (EACCES / ENOENT), which
is why the v1.0.0 Android scanner detected no files. Android 11+ apps must
go through MediaStore (or SAF). The bridge answers `queryAudioTracks` with
every music file the system indexer knows about (path + coarse tags), and
requests READ_MEDIA_AUDIO (API 33+) / READ_EXTERNAL_STORAGE (API < 33) on
first use.

Run this after scaffolding (release.yml and e2e.yml do the same in CI):

    python3 tools/patch_android_media_store.py

Idempotent: running it twice changes nothing. Exits 0 with a note when no
Android runner is present (e.g. scaffolded for desktop only).
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

APP_DIR = Path("android") / "app"
MAIN_SRC = APP_DIR / "src" / "main"
MANIFEST = MAIN_SRC / "AndroidManifest.xml"

PERMISSION_LINES = (
    '    <uses-permission '
    'android:name="android.permission.READ_EXTERNAL_STORAGE" '
    'android:maxSdkVersion="32" />\n'
    '    <uses-permission android:name="android.permission.READ_MEDIA_AUDIO" />'
)

# The Kotlin implementation is written with a __PACKAGE__ placeholder and
# the real package name is detected from the scaffolded runner (never
# hardcoded, so an org change cannot desync the Dart/native contract).
MAIN_ACTIVITY_TEMPLATE = """package __PACKAGE__

import android.Manifest
import android.content.pm.PackageManager
import android.os.Build
import android.provider.MediaStore
import io.flutter.embedding.android.FlutterActivity
import io.flutter.embedding.engine.FlutterEngine
import io.flutter.plugin.common.MethodChannel

/**
 * Wavely Android shell with a MediaStore audio bridge.
 *
 * `tools/patch_android_media_store.py` writes this file over the
 * flutter-create template. The bridge is the Android 10+ (scoped storage)
 * answer to library scanning: instead of walking the filesystem with
 * dart:io — which returns EACCES/ENOENT for third-party audio on
 * Android 11+ — the Dart scanner queries MediaStore here and receives the
 * concrete file paths of every music file the system indexer knows about.
 *
 * Channel contract (`wavely/media_store`):
 * - `queryAudioTracks` ->
 *   `{ 'granted': bool, 'tracks': List<Map<String, Any>> }` where every
 *   track map carries `path`, `title`, `artist`, `album`, `durationMs`,
 *   `size`. The first call requests the media permission when missing;
 *   the result resolves after the user answers the system dialog.
 */
class MainActivity : FlutterActivity() {
    companion object {
        private const val MEDIA_STORE_CHANNEL = "wavely/media_store"
        private const val SAF_CHANNEL = "wavely/saf"
        private const val PERMISSION_REQUEST_CODE = 4711
    }

    private var pendingMediaStoreResult: MethodChannel.Result? = null

    override fun configureFlutterEngine(flutterEngine: FlutterEngine) {
        super.configureFlutterEngine(flutterEngine)
        val messenger = flutterEngine.dartExecutor.binaryMessenger

        MethodChannel(messenger, MEDIA_STORE_CHANNEL).setMethodCallHandler { call, result ->
            when (call.method) {
                "queryAudioTracks" -> handleQueryAudioTracks(result)
                else -> result.notImplemented()
            }
        }

        // Stage 1.1 SAF contract: the Dart side degrades gracefully when
        // the handler answers `false` (plain paths are kept; MediaStore
        // covers the actual scanning).
        MethodChannel(messenger, SAF_CHANNEL).setMethodCallHandler { _, result ->
            result.success(false)
        }
    }

    private fun audioPermissions(): Array<String> =
        if (Build.VERSION.SDK_INT >= 33) {
            arrayOf(Manifest.permission.READ_MEDIA_AUDIO)
        } else {
            arrayOf(Manifest.permission.READ_EXTERNAL_STORAGE)
        }

    private fun handleQueryAudioTracks(result: MethodChannel.Result) {
        val missing = audioPermissions().filter {
            checkSelfPermission(it) != PackageManager.PERMISSION_GRANTED
        }
        if (missing.isEmpty()) {
            result.success(mapOf("granted" to true, "tracks" to queryAudioTracks()))
            return
        }
        pendingMediaStoreResult = result
        requestPermissions(missing.toTypedArray(), PERMISSION_REQUEST_CODE)
    }

    override fun onRequestPermissionsResult(
        requestCode: Int,
        permissions: Array<out String>,
        grantResults: IntArray
    ) {
        super.onRequestPermissionsResult(requestCode, permissions, grantResults)
        if (requestCode != PERMISSION_REQUEST_CODE) {
            return
        }
        val pending = pendingMediaStoreResult
        pendingMediaStoreResult = null
        if (pending == null) {
            return
        }
        val granted = grantResults.isNotEmpty() &&
            grantResults[0] == PackageManager.PERMISSION_GRANTED
        if (granted) {
            pending.success(mapOf("granted" to true, "tracks" to queryAudioTracks()))
        } else {
            pending.success(mapOf("granted" to false, "tracks" to emptyList<Map<String, Any>>()))
        }
    }

    private fun queryAudioTracks(): List<Map<String, Any>> {
        val projection = arrayOf(
            MediaStore.Audio.Media._ID,
            MediaStore.Audio.Media.DATA,
            MediaStore.Audio.Media.TITLE,
            MediaStore.Audio.Media.ARTIST,
            MediaStore.Audio.Media.ALBUM,
            MediaStore.Audio.Media.DURATION,
            MediaStore.Audio.Media.SIZE
        )
        val selection = MediaStore.Audio.Media.IS_MUSIC + " != 0"
        val sortOrder = MediaStore.Audio.Media.TITLE + " COLLATE NOCASE ASC"
        val tracks = mutableListOf<Map<String, Any>>()
        try {
            contentResolver.query(
                MediaStore.Audio.Media.EXTERNAL_CONTENT_URI,
                projection,
                selection,
                null,
                sortOrder
            )?.use { cursor ->
                while (cursor.moveToNext()) {
                    val path = cursor.getString(1) ?: continue
                    if (path.isEmpty()) {
                        continue
                    }
                    val row = HashMap<String, Any>(6)
                    row["path"] = path
                    row["title"] = cursor.getString(2) ?: ""
                    row["artist"] = cursor.getString(3) ?: ""
                    row["album"] = cursor.getString(4) ?: ""
                    row["durationMs"] = cursor.getLong(5)
                    row["size"] = cursor.getLong(6)
                    tracks.add(row)
                }
            }
        } catch (_: Exception) {
            // A failed query returns what was collected so far; the Dart
            // side surfaces per-file errors through the scan event stream.
        }
        return tracks
    }
}
"""


def detect_package() -> str | None:
    """Detects the application package from the scaffolded runner files."""
    for parent in ("kotlin", "java"):
        for candidate in sorted((MAIN_SRC / parent).rglob("*Activity.kt")):
            match = re.search(r"^package\s+([\w.]+)", candidate.read_text(encoding="utf-8"), re.M)
            if match:
                return match.group(1)
    for build_file in (APP_DIR / "build.gradle.kts", APP_DIR / "build.gradle"):
        if build_file.exists():
            match = re.search(r'applicationId\s*=?\s*"([^"]+)"', build_file.read_text(encoding="utf-8"))
            if match:
                return match.group(1)
    return None


def patch_manifest() -> bool:
    src = MANIFEST.read_text(encoding="utf-8")
    if "READ_MEDIA_AUDIO" in src:
        print(f"[patch] {MANIFEST}: media permissions already declared")
        return True
    needle = "<application"
    index = src.find(needle)
    if index < 0:
        print(f"[patch] ERROR: no <application tag found in {MANIFEST}")
        return False
    src = src[:index] + PERMISSION_LINES + "\n" + src[index:]
    MANIFEST.write_text(src, encoding="utf-8")
    print(f"[patch] {MANIFEST}: declared READ_MEDIA_AUDIO + legacy READ_EXTERNAL_STORAGE")
    return True


def patch_main_activity(package: str) -> bool:
    # Kotlin source lives under kotlin/ (or java/ for legacy scaffolds); the
    # package segments always mirror the directory layout.
    segments = package.split(".")
    target = MAIN_SRC / "kotlin" / Path(*segments) / "MainActivity.kt"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(
        MAIN_ACTIVITY_TEMPLATE.replace("__PACKAGE__", package),
        encoding="utf-8",
    )
    print(f"[patch] {target}: wrote MediaStore bridge MainActivity (package {package})")
    return True


def main() -> int:
    if not APP_DIR.exists():
        print(
            "[patch] no Android runner found (android/app missing) — "
            "scaffold it first with `flutter create . --platforms=android`"
        )
        return 0
    package = detect_package()
    if package is None:
        print("[patch] ERROR: could not detect the application package")
        return 1
    if not patch_manifest():
        return 1
    if not patch_main_activity(package):
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
