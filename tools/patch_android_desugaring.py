#!/usr/bin/env python3
"""Patch the scaffolded Android runner for Wavely's plugin set.

The repo does not commit platform runner folders (see README "Getting
Started"): they are generated by `flutter create .`. The default template
needs two adjustments for the plugin set:

1. Core library desugaring — `flutter_local_notifications` (>= 19)
   REQUIRES it; Gradle fails at `:app:checkReleaseAarMetadata` with:

       Dependency ':flutter_local_notifications' requires core library
       desugaring to be enabled for :app.

2. minSdk 26 — `sentry_flutter` declares minSdk 26; the template default
   (flutter.minSdkVersion = 24) fails the manifest merger with:

       uses-sdk:minSdkVersion 24 cannot be smaller than version 26
       declared in library [:sentry_flutter]

Run this after scaffolding (release.yml does the same in CI):

    python3 tools/patch_android_desugaring.py

Handles both the Kotlin DSL (android/app/build.gradle.kts, the modern
default) and the legacy Groovy DSL (android/app/build.gradle). Idempotent:
running it twice changes nothing. Exits 0 with a note when no Android
runner is present (e.g. scaffolded for desktop only).
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

DESUGAR_LIB = "com.android.tools:desugar_jdk_libs:2.1.5"
APP_DIR = Path("android") / "app"


def patch_kts(path: Path) -> bool:
    src = path.read_text(encoding="utf-8")

    # 1. Flip the compileOptions switch inside the android block.
    if "coreLibraryDesugaring" in src:
        print(f"[patch] {path}: desugaring already enabled")
    else:
        updated, n = re.subn(
            r"(compileOptions\s*\{)",
            r"\1\n        isCoreLibraryDesugaringEnabled = true",
            src,
            count=1,
        )
        if n != 1:
            print(f"[patch] ERROR: no compileOptions block found in {path}")
            return False
        src = updated
        # 2. Add the desugaring artifact to the (possibly missing)
        #    dependencies block. The modern template ships without one.
        if re.search(r"^dependencies\s*\{", src, re.M):
            src = re.sub(
                r"(^dependencies\s*\{)",
                rf"\1\n    coreLibraryDesugaring(\"{DESUGAR_LIB}\")",
                src,
                count=1,
                flags=re.M,
            )
        else:
            src += (
                "\n\ndependencies {\n"
                f"    coreLibraryDesugaring(\"{DESUGAR_LIB}\")\n"
                "}\n"
            )
        print(f"[patch] {path}: enabled core library desugaring ({DESUGAR_LIB})")

    # 3. Raise minSdk to 26 (sentry_flutter requirement). Replace the whole
    #    RHS (e.g. `flutter.minSdkVersion`), not just the first word.
    m = re.search(r"minSdk\s*=\s*([^\n]+)", src)
    if not m:
        print(f"[patch] ERROR: no minSdk line found in {path}")
        return False
    current = m.group(1).strip()
    if current.isdigit() and int(current) >= 26:
        print(f"[patch] {path}: minSdk already {current}")
    else:
        src = re.sub(
            r"minSdk\s*=\s*[^\n]+",
            "minSdk = 26",
            src,
            count=1,
        )
        print(f"[patch] {path}: minSdk {current} -> 26 (sentry_flutter requirement)")

    path.write_text(src, encoding="utf-8")
    return True


def patch_groovy(path: Path) -> bool:
    src = path.read_text(encoding="utf-8")

    if "coreLibraryDesugaring" in src:
        print(f"[patch] {path}: desugaring already enabled")
    else:
        updated, n = re.subn(
            r"(compileOptions\s*\{)",
            r"\1\n        coreLibraryDesugaringEnabled true",
            src,
            count=1,
        )
        if n != 1:
            print(f"[patch] ERROR: no compileOptions block found in {path}")
            return False
        src = updated
        if re.search(r"^dependencies\s*\{", src, re.M):
            src = re.sub(
                r"(^dependencies\s*\{)",
                rf"\1\n    coreLibraryDesugaring '{DESUGAR_LIB}'",
                src,
                count=1,
                flags=re.M,
            )
        else:
            src += (
                "\n\ndependencies {\n"
                f"    coreLibraryDesugaring '{DESUGAR_LIB}'\n"
                "}\n"
            )
        print(f"[patch] {path}: enabled core library desugaring ({DESUGAR_LIB})")

    # Raise minSdk to 26 (sentry_flutter requirement). Replace the whole
    # RHS (e.g. `flutter.minSdkVersion`), not just the first word.
    m = re.search(r"minSdkVersion\s+([^\n]+)", src)
    if not m:
        print(f"[patch] ERROR: no minSdkVersion line found in {path}")
        return False
    current = m.group(1).strip()
    if current.isdigit() and int(current) >= 26:
        print(f"[patch] {path}: minSdk already {current}")
    else:
        src = re.sub(
            r"minSdkVersion\s+[^\n]+",
            "minSdkVersion 26",
            src,
            count=1,
        )
        print(f"[patch] {path}: minSdk {current} -> 26 (sentry_flutter requirement)")

    path.write_text(src, encoding="utf-8")
    return True


def main() -> int:
    kts = APP_DIR / "build.gradle.kts"
    groovy = APP_DIR / "build.gradle"
    if kts.exists():
        return 0 if patch_kts(kts) else 1
    if groovy.exists():
        return 0 if patch_groovy(groovy) else 1
    print("[patch] no Android runner found (android/app/build.gradle*) — "
          "scaffold it first with `flutter create . --platforms=android`")
    return 0


if __name__ == "__main__":
    sys.exit(main())
