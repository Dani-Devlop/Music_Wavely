#!/usr/bin/env python3
"""Wire the committed Wavely release keystore into the scaffolded runner.

The repo does not commit platform runner folders (see README "Getting
Started"): the Android runner is generated by `flutter create .` in CI.
The template signs release builds with the DEBUG key
(`signingConfig = signingConfigs.getByName("debug")`). On ephemeral CI
runners that debug keystore is regenerated on every run, so every
release APK carried a DIFFERENT signature — installing an update over
an existing install failed with:

    App not installed as package conflicts with an existing package.

Fix (docs/PACKAGING.md §signing): the repo ships a shared keystore at
`android/signing/wavely-release.jks` + `android/signing/key.properties`
(deliberate exception to the `*.jks` ignore rule). This patch — run
AFTER `flutter create . --platforms=android` — adds a `wavelyRelease`
signing config that reads key.properties and points `buildTypes.release`
at it, falling back to debug signing when the keystore is absent (e.g.
a fork without the signing folder must still build).

Run this after scaffolding (release.yml does the same in CI):

    python3 tools/patch_android_signing.py

Handles both the Kotlin DSL (android/app/build.gradle.kts, the modern
default) and the legacy Groovy DSL (android/app/build.gradle). Idempotent:
running it twice changes nothing. Exits 0 with a note when no Android
runner is present (e.g. scaffolded for desktop only).
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

APP_DIR = Path("android") / "app"
MARKER = "wavelyRelease"


def _preamble_kts() -> str:
    return (
        "\n// Wavely: stable release signing (docs/PACKAGING.md §signing). Reads\n"
        "// android/signing/key.properties (committed) so every build — local or\n"
        "// CI — signs with the SAME key and updates install over existing\n"
        "// installs without \"package conflicts with an existing package\".\n"
        "val wavelySigningProperties = java.util.Properties().apply {\n"
        "    val f = rootProject.file(\"signing/key.properties\")\n"
        "    if (f.exists()) f.inputStream().use { load(it) }\n"
        "}\n"
        "val wavelyHasReleaseKeystore = wavelySigningProperties.getProperty(\"storeFile\") != null\n\n"
    )


def _config_block_kts() -> str:
    return (
        "    signingConfigs {\n"
        "        if (wavelyHasReleaseKeystore) {\n"
        "            create(\"wavelyRelease\") {\n"
        "                keyAlias = wavelySigningProperties.getProperty(\"keyAlias\")\n"
        "                keyPassword = wavelySigningProperties.getProperty(\"keyPassword\")\n"
        "                storeFile = rootProject.file(wavelySigningProperties.getProperty(\"storeFile\"))\n"
        "                storePassword = wavelySigningProperties.getProperty(\"storePassword\")\n"
        "            }\n"
        "        }\n"
        "    }\n\n"
    )


def _preamble_groovy() -> str:
    return (
        "\n// Wavely: stable release signing (docs/PACKAGING.md §signing). Reads\n"
        "// android/signing/key.properties (committed) so every build — local or\n"
        "// CI — signs with the SAME key and updates install over existing\n"
        "// installs without \"package conflicts with an existing package\".\n"
        "def wavelySigningProperties = new Properties()\n"
        "def wavelySigningFile = rootProject.file('signing/key.properties')\n"
        "if (wavelySigningFile.exists()) {\n"
        "    wavelySigningFile.withInputStream { wavelySigningProperties.load(it) }\n"
        "}\n"
        "def wavelyHasReleaseKeystore = wavelySigningProperties['storeFile'] != null\n\n"
    )


def _config_block_groovy() -> str:
    return (
        "    signingConfigs {\n"
        "        wavelyRelease {\n"
        "            if (wavelyHasReleaseKeystore) {\n"
        "                keyAlias wavelySigningProperties['keyAlias']\n"
        "                keyPassword wavelySigningProperties['keyPassword']\n"
        "                storeFile rootProject.file(wavelySigningProperties['storeFile'])\n"
        "                storePassword wavelySigningProperties['storePassword']\n"
        "            }\n"
        "        }\n"
        "    }\n\n"
    )


def patch_kts(path: Path) -> bool:
    src = path.read_text(encoding="utf-8")

    if MARKER in src:
        print(f"[patch] {path}: release signing already wired")
        return True

    # 1. Properties preamble BEFORE the android block (top-level vals).
    updated, n = re.subn(r"(?m)^android\s*\{", _preamble_kts() + "android {", src, count=1)
    if n != 1:
        print(f"[patch] ERROR: no top-level `android {{` block found in {path}")
        return False
    src = updated

    # 2. signingConfigs block right after `android {`.
    updated, n = re.subn(r"(?m)^android\s*\{\n", "android {\n" + _config_block_kts(), src, count=1)
    if n != 1:
        print(f"[patch] ERROR: could not insert signingConfigs into {path}")
        return False
    src = updated

    # 3. Point buildTypes.release at the stable keystore (debug fallback).
    replacement = (
        "signingConfig = if (wavelyHasReleaseKeystore) signingConfigs.getByName(\"wavelyRelease\") "
        "else signingConfigs.getByName(\"debug\")"
    )
    updated, n = re.subn(
        r"signingConfig\s*=\s*signingConfigs\.getByName\(\"debug\"\)",
        replacement,
        src,
        count=1,
    )
    if n != 1:
        print(f"[patch] ERROR: no debug signingConfig line found in {path}")
        return False
    src = updated

    path.write_text(src, encoding="utf-8")
    print(f"[patch] {path}: release builds now sign with the committed wavelyRelease keystore")
    return True


def patch_groovy(path: Path) -> bool:
    src = path.read_text(encoding="utf-8")

    if MARKER in src:
        print(f"[patch] {path}: release signing already wired")
        return True

    # 1. Properties preamble BEFORE the android block.
    updated, n = re.subn(r"(?m)^android\s*\{", _preamble_groovy() + "android {", src, count=1)
    if n != 1:
        print(f"[patch] ERROR: no top-level `android {{` block found in {path}")
        return False
    src = updated

    # 2. signingConfigs block right after `android {`.
    updated, n = re.subn(r"(?m)^android\s*\{\n", "android {\n" + _config_block_groovy(), src, count=1)
    if n != 1:
        print(f"[patch] ERROR: could not insert signingConfigs into {path}")
        return False
    src = updated

    # 3. Point buildTypes.release at the stable keystore (debug fallback).
    replacement = (
        "signingConfig wavelyHasReleaseKeystore ? signingConfigs.wavelyRelease : signingConfigs.debug"
    )
    updated, n = re.subn(
        r"signingConfig\s+signingConfigs\.debug",
        replacement,
        src,
        count=1,
    )
    if n != 1:
        print(f"[patch] ERROR: no debug signingConfig line found in {path}")
        return False
    src = updated

    path.write_text(src, encoding="utf-8")
    print(f"[patch] {path}: release builds now sign with the committed wavelyRelease keystore")
    return True


def main() -> int:
    kts = APP_DIR / "build.gradle.kts"
    groovy = APP_DIR / "build.gradle"
    if kts.exists():
        return 0 if patch_kts(kts) else 1
    if groovy.exists():
        return 0 if patch_groovy(groovy) else 1
    print("[patch] no Android runner found (android/app/build.gradle*) — "
          "scaffold it first with `flutter create . --platforms=android`")
    return 0


if __name__ == "__main__":
    sys.exit(main())
