#!/usr/bin/env python3
"""Patch the scaffolded Android runner with Wavely system integrations.

Phase 9 (system integrations) platform-side pieces. The repo does not
commit platform runner folders (see README "Getting Started"): they are
generated by `flutter create .` — the same pattern as
patch_android_desugaring.py / patch_android_media_store.py. This script
adds:

1. **Home-screen widgets (Phase 9.2)** — three AppWidgetProviders reading
   the `home_widget` plugin storage (SharedPreferences file
   `HomeWidgetPreferences`, keys defined in
   `lib/playback/widgets/widget_sync.dart`):
   - `WavelyWidgetSmall`  — 4×1, track title + artist.
   - `WavelyWidgetControls` — 4×1, title/artist + prev / play-pause / next.
   - `WavelyWidgetLarge`  — 3×4, album art + title + controls.
   Widget buttons broadcast the `WAVELY_*` actions handled by
   `WavelyWidgetActionReceiver`, which dispatches standard media key events
   through `AudioManager` — Android routes them to the active
   MediaSession (audio_service), so no background Dart engine is spawned.
2. **Quick-settings tile (Phase 9.3)** — `WavelyPlaybackTileService`
   (play/pause toggle, active state mirrors `wavely_playing`).
3. **audio_service manifest plumbing** — the AudioService MediaBrowser
   service (foregroundServiceType mediaPlayback, MediaBrowserService +
   MEDIA_BUTTON intent filters → lock screen / Bluetooth / Android Auto
   surfaces) and the MediaButtonReceiver. Also flips the patched
   MainActivity to extend `AudioServiceActivity` (required by
   audio_service to attach the session to the Flutter engine).
4. **Android Auto media browse (Phase 9)** — the MediaBrowserService
   intent filter above is what Android Auto connects to; the handler's
   queue becomes the browse list.

Run after scaffolding (release.yml does the same in CI):

    python3 tools/patch_android_widgets.py

Idempotent: running it twice changes nothing. Exits 0 with a note when no
Android runner is present (e.g. scaffolded for desktop only).
"""

