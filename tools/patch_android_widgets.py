def detect_package() -> str | None:
    """Detects the application package from the scaffolded runner files."""
    for parent in ("kotlin", "java"):
        for candidate in sorted((MAIN_SRC / parent).rglob("*Activity.kt")):
            match = re.search(
                r"^package\s+([\w.]+)",
                candidate.read_text(encoding="utf-8"),
                re.M,
            )
            if match:
                return match.group(1)
    for build_file in (APP_DIR / "build.gradle.kts", APP_DIR / "build.gradle"):
        if build_file.exists():
            match = re.search(
                r'applicationId\s*=?\s*"([^"]+)"',
                build_file.read_text(encoding="utf-8"),
            )
            if match:
                return match.group(1)
    return None


def write_kotlin(package: str) -> list[str]:
    segments = package.split(".")
    target_dir = MAIN_SRC / "kotlin" / Path(*segments)
    target_dir.mkdir(parents=True, exist_ok=True)
    written: list[str] = []
    files = {
        "WavelyWidgetSmall.kt": WIDGET_SMALL,
        "WavelyWidgetControls.kt": WIDGET_CONTROLS,
        "WavelyWidgetLarge.kt": WIDGET_LARGE,
        "WavelyWidgetActionReceiver.kt": WIDGET_ACTION_RECEIVER,
        "WavelyPlaybackTileService.kt": TILE_SERVICE,
    }
    for name, template in files.items():
        target = target_dir / name
        content = template.replace("__PACKAGE__", package)
        if target.exists() and target.read_text(encoding="utf-8") == content:
            continue
        target.write_text(content, encoding="utf-8")
        written.append(str(target))
    return written


def write_resources() -> list[str]:
    layout_dir = MAIN_SRC / "res" / "layout"
    xml_dir = MAIN_SRC / "res" / "xml"
    layout_dir.mkdir(parents=True, exist_ok=True)
    xml_dir.mkdir(parents=True, exist_ok=True)
    written: list[str] = []
    resources = {
        (layout_dir, "widget_small.xml"): LAYOUT_SMALL,
        (layout_dir, "widget_controls.xml"): LAYOUT_CONTROLS,
        (layout_dir, "widget_large.xml"): LAYOUT_LARGE,
        (xml_dir, "widget_small_info.xml"): WIDGET_SMALL_INFO,
        (xml_dir, "widget_controls_info.xml"): WIDGET_CONTROLS_INFO,
        (xml_dir, "widget_large_info.xml"): WIDGET_LARGE_INFO,
    }
    for (target_dir, name), content in resources.items():
        target = target_dir / name
        if target.exists() and target.read_text(encoding="utf-8") == content:
            continue
        target.write_text(content, encoding="utf-8")
        written.append(str(target))
    return written


def patch_permissions() -> bool:
    src = MANIFEST.read_text(encoding="utf-8")
    if "FOREGROUND_SERVICE_MEDIA_PLAYBACK" in src:
        print(f"[patch] {MANIFEST}: foreground-service media permission already declared")
        return True
    needle = "<application"
    index = src.find(needle)
    if index < 0:
        print(f"[patch] ERROR: no <application tag found in {MANIFEST}")
        return False
    src = src[:index] + WIDGET_PERMISSION_LINES + "\n" + src[index:]
    MANIFEST.write_text(src, encoding="utf-8")
    print(f"[patch] {MANIFEST}: declared FOREGROUND_SERVICE(_MEDIA_PLAYBACK)")
    return True


def patch_application_content() -> bool:
    src = MANIFEST.read_text(encoding="utf-8")
    additions = ""
    if "com.ryanheise.audioservice.AudioService" not in src:
        additions += AUDIO_SERVICE_BLOCK + "\n"
    if "WavelyWidgetSmall" not in src:
        additions += MANIFEST_BLOCK + "\n"
    if not additions:
        print(f"[patch] {MANIFEST}: widgets / tile / audio_service already registered")
        return True
    needle = "</application>"
    index = src.find(needle)
    if index < 0:
        print(f"[patch] ERROR: no </application> tag found in {MANIFEST}")
        return False
    src = src[:index] + additions + src[index:]
    MANIFEST.write_text(src, encoding="utf-8")
    print(f"[patch] {MANIFEST}: registered widgets, QS tile, audio_service (Android Auto)")
    return True


def patch_main_activity(package: str) -> bool:
    """Ensures MainActivity extends AudioServiceActivity (audio_service)."""
    target = None
    for parent in ("kotlin", "java"):
        for candidate in sorted((MAIN_SRC / parent).rglob("*Activity.kt")):
            if candidate.name == "MainActivity.kt":
                target = candidate
                break
    if target is None:
        print("[patch] MainActivity.kt not found — run patch_android_media_store.py first")
        return False
    src = target.read_text(encoding="utf-8")
    if "AudioServiceActivity" in src:
        print(f"[patch] {target}: already extends AudioServiceActivity")
        return True
    src = src.replace(
        "import io.flutter.embedding.android.FlutterActivity",
        "import com.ryanheise.audioservice.AudioServiceActivity\n"
        "import io.flutter.embedding.android.FlutterActivity",
    )
    src = src.replace(
        "class MainActivity : FlutterActivity()",
        "class MainActivity : AudioServiceActivity()",
    )
    target.write_text(src, encoding="utf-8")
    print(f"[patch] {target}: MainActivity now extends AudioServiceActivity")
    return True


def main() -> int:
    if not APP_DIR.exists():
        print(
            "[patch] no Android runner found (android/app missing) — "
            "scaffold it first with `flutter create . --platforms=android`"
        )
        return 0
    package = detect_package()
    if package is None:
        print("[patch] ERROR: could not detect the application package")
        return 1
    if not patch_permissions():
        return 1
    if not patch_application_content():
        return 1
    if not patch_main_activity(package):
        return 1
    for path in write_kotlin(package) + write_resources():
        print(f"[patch] {path}: wrote")
    return 0


if __name__ == "__main__":
    sys.exit(main())
